#!/usr/bin/env node
// Auto-embed `oe graph` Mermaid diagrams into every example's docs.
//
// For each examples/<name>/experience.yaml, render the DAG with the same
// renderMermaid() the `oe graph` command uses, then inject a fenced ```mermaid
// block (between HTML-comment markers) into BOTH:
//   - examples/<name>/README.md
//   - site/examples/<name>.md   (when that page exists)
//
// Idempotent: re-running replaces the marked block in place, producing zero
// diff. Designed to be prettier-stable so `gen → prettier → gen` converges.
//
// Build the dist first (this script imports the built output, it does not
// build): `pnpm --filter @openexpertise/schema build && pnpm --filter
// @openexpertise/cli build` then `node scripts/gen-example-diagrams.mjs`.
//
// Exits non-zero on any parse/render error so it can gate CI.

import { readFileSync, writeFileSync, existsSync, readdirSync, statSync } from 'node:fs'
import { fileURLToPath } from 'node:url'
import { dirname, join, relative } from 'node:path'

import { renderMermaid } from '../packages/cli/dist/render-mermaid.js'
import { parseExperienceYaml } from '../packages/schema/dist/index.js'

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(__dirname, '..')

const MARKER_START =
  '<!-- oe-graph:start (generated by scripts/gen-example-diagrams.mjs — do not edit by hand) -->'
const MARKER_END = '<!-- oe-graph:end -->'
// Matches an existing block (start marker through end marker, inclusive),
// regardless of what it currently wraps. Robust to prettier reflow.
const BLOCK_RE = /<!-- oe-graph:start[\s\S]*?<!-- oe-graph:end -->/

/** Build the marked, fenced mermaid block for a rendered spec. */
function makeBlock(mermaid) {
  // renderMermaid() returns a trailing newline; trim so the fence wraps the
  // diagram with exactly one newline before the closing fence — this is the
  // shape prettier leaves untouched.
  const body = mermaid.replace(/\n+$/, '')
  return [MARKER_START, '', '```mermaid', body, '```', '', MARKER_END].join('\n')
}

/**
 * Inject (replace-or-insert) the block into `content`.
 * @param {string} content existing file text
 * @param {string} block the marked block to embed
 * @param {(content: string, block: string) => string} insert how to insert
 *   when no markers exist yet
 * @returns {string}
 */
function inject(content, block, insert) {
  if (BLOCK_RE.test(content)) {
    return content.replace(BLOCK_RE, block)
  }
  return insert(content, block)
}

/** Split a file into lines, preserving a trailing-newline flag. */
function ensureTrailingNewline(s) {
  return s.endsWith('\n') ? s : s + '\n'
}

/**
 * README insertion: place a `## Diagram` section right after the intro —
 * i.e. after the first `# ` heading and the paragraph(s) that immediately
 * follow it, but before the first fenced code block or the first `## `.
 */
function insertIntoReadme(content, block) {
  const lines = content.split('\n')
  // Find the first `# ` heading (level-1). Fall back to line 0.
  let headingIdx = lines.findIndex((l) => /^# /.test(l))
  if (headingIdx === -1) headingIdx = 0

  // Walk forward from just after the heading to find the insertion point:
  // the first line that begins a fenced block (```) or a `## ` subheading.
  let insertAt = lines.length
  for (let i = headingIdx + 1; i < lines.length; i++) {
    const l = lines[i]
    if (/^```/.test(l) || /^## /.test(l)) {
      insertAt = i
      break
    }
  }

  const section = ['## Diagram', '', block, '']
  // Ensure exactly one blank line separates the preceding content from our
  // section: trim trailing blanks in the head, then add one.
  const head = lines.slice(0, insertAt)
  while (head.length > 0 && head[head.length - 1].trim() === '') head.pop()
  const tail = lines.slice(insertAt)
  const rebuilt = [...head, '', ...section, ...tail].join('\n')
  return ensureTrailingNewline(rebuilt)
}

/**
 * Site-page insertion. Never touch frontmatter. If a `## The graph` heading
 * exists, insert the block right after it (so the rendered diagram sits with
 * the existing ASCII art). Otherwise add a `## Diagram` section after the
 * first `# ` heading + its intro.
 */
function insertIntoSite(content, block) {
  const lines = content.split('\n')

  // Locate end of frontmatter (a leading `---` ... `---`) so we never inject
  // inside it.
  let bodyStart = 0
  if (lines[0] === '---') {
    for (let i = 1; i < lines.length; i++) {
      if (lines[i] === '---') {
        bodyStart = i + 1
        break
      }
    }
  }

  // Prefer inserting after a `## The graph` heading.
  const graphIdx = lines.findIndex((l, i) => i >= bodyStart && /^## The graph\s*$/.test(l))
  if (graphIdx !== -1) {
    const head = lines.slice(0, graphIdx + 1)
    const tail = lines.slice(graphIdx + 1)
    // Drop leading blank lines in the tail so we control the spacing.
    while (tail.length > 0 && tail[0].trim() === '') tail.shift()
    const rebuilt = [...head, '', block, '', ...tail].join('\n')
    return ensureTrailingNewline(rebuilt)
  }

  // Otherwise: after the first `# ` heading + intro, before first `## ` /
  // fence (same rule as README), but never before bodyStart.
  let headingIdx = lines.findIndex((l, i) => i >= bodyStart && /^# /.test(l))
  if (headingIdx === -1) headingIdx = bodyStart - 1 // insert just after frontmatter

  let insertAt = lines.length
  for (let i = headingIdx + 1; i < lines.length; i++) {
    if (/^```/.test(lines[i]) || /^## /.test(lines[i])) {
      insertAt = i
      break
    }
  }
  const section = ['## Diagram', '', block, '']
  const head = lines.slice(0, insertAt)
  while (head.length > 0 && head[head.length - 1].trim() === '') head.pop()
  const tail = lines.slice(insertAt)
  const rebuilt = [...head, '', ...section, ...tail].join('\n')
  return ensureTrailingNewline(rebuilt)
}

function main() {
  const examplesDir = join(repoRoot, 'examples')
  const siteDir = join(repoRoot, 'site', 'examples')

  const names = readdirSync(examplesDir)
    .filter((n) => {
      const p = join(examplesDir, n)
      return statSync(p).isDirectory() && existsSync(join(p, 'experience.yaml'))
    })
    .sort()

  const updated = []
  let errors = 0

  for (const name of names) {
    const yamlPath = join(examplesDir, name, 'experience.yaml')
    let block
    try {
      const spec = parseExperienceYaml(readFileSync(yamlPath, 'utf8'))
      const mermaid = renderMermaid(spec)
      block = makeBlock(mermaid)
    } catch (err) {
      console.error(`✗ ${relative(repoRoot, yamlPath)} — ${err.message ?? err}`)
      errors++
      continue
    }

    const targets = [
      { path: join(examplesDir, name, 'README.md'), insert: insertIntoReadme },
      { path: join(siteDir, `${name}.md`), insert: insertIntoSite },
    ]

    for (const { path, insert } of targets) {
      if (!existsSync(path)) continue
      const before = readFileSync(path, 'utf8')
      const after = inject(before, block, insert)
      if (after !== before) {
        writeFileSync(path, after)
        updated.push(relative(repoRoot, path))
        console.log(`✓ ${relative(repoRoot, path)}`)
      }
    }
  }

  if (updated.length === 0) console.log('(no changes — all diagrams up to date)')
  console.log(`\n${names.length} examples processed, ${updated.length} file(s) updated.`)

  if (errors > 0) {
    console.error(`\n${errors} example(s) failed to parse/render.`)
    process.exit(1)
  }
}

main()
